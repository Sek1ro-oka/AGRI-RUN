    private static List<CampusPoint> toPoints(double[] flat) {
        List<CampusPoint> points = new ArrayList<>(flat.length / 2);
        for (int i = 0; i + 1 < flat.length; i += 2) {
            points.add(new CampusPoint(flat[i], flat[i + 1]));
        }
        return points;
    }

